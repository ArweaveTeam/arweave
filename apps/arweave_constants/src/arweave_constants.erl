%% Test-only overrides let simulations exercise mainnet-sized footprints.
%% All applications read the same values, including derived geometry.
partition_size() ->
    persistent_term:get({?MODULE, partition_size}, ?PARTITION_SIZE).

replica_2_9_entropy_size() ->
    persistent_term:get({?MODULE, entropy_size}, ?REPLICA_2_9_ENTROPY_SIZE).

replica_2_9_entropy_count() ->
    persistent_term:get({?MODULE, entropy_count}, ?REPLICA_2_9_ENTROPY_COUNT).

internal_override_partition_size(Size) ->
    persistent_term:put({?MODULE, partition_size}, Size).

internal_reset_partition_size_override() ->
    persistent_term:erase({?MODULE, partition_size}),
    ok.

internal_override_replica_2_9_entropy_size(Size) ->
    persistent_term:put({?MODULE, entropy_size}, Size).

internal_override_replica_2_9_entropy_count(Count) ->
    persistent_term:put({?MODULE, entropy_count}, Count).

internal_reset_replica_2_9_overrides() ->
    persistent_term:erase({?MODULE, entropy_size}),
    persistent_term:erase({?MODULE, entropy_count}),
    ok.
